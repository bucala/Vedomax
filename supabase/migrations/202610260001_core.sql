create table public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 username text not null check (char_length(username) between 3 and 24),
 avatar_url text, experience_points integer not null default 0 check (experience_points >= 0),
 streak_days integer not null default 0 check (streak_days >= 0),
 last_active_at timestamptz, created_at timestamptz not null default now()
);
create table public.subjects (
 id integer generated by default as identity primary key,
 name_sk text not null, slug text not null unique
);
create table public.topics (
 id integer generated by default as identity primary key,
 subject_id integer not null references public.subjects(id),
 grade integer not null check (grade in (8,9)), title_sk text not null,
 order_index integer not null check (order_index >= 0),
 curriculum_status text not null default 'draft' check (curriculum_status in ('draft','reviewed')),
 curriculum_source text, curriculum_standard text,
 unique(subject_id, grade, order_index),
 check (curriculum_status <> 'reviewed' or (curriculum_source is not null and curriculum_standard is not null))
);
create table public.lessons (
 id integer generated by default as identity primary key,
 topic_id integer not null references public.topics(id), title_sk text not null,
 type text not null check (type in ('theory','minigame','boss_fight')),
 lottie_asset_path text not null default 'assets/animations/success.json',
 time_limit_seconds integer not null default 120 check(time_limit_seconds between 10 and 600)
);
create table public.questions (
 id uuid primary key default gen_random_uuid(),
 lesson_id integer not null references public.lessons(id) on delete cascade,
 question_text_sk text not null,
 mechanic_type text not null check(mechanic_type in ('detective','rpg_chat','puzzle_calc','drag_drop','geo_click')),
 content_json jsonb not null check(jsonb_typeof(content_json) = 'object'),
 order_index integer not null default 0,
 unique(lesson_id,order_index)
);
create table private.question_keys (
 question_id uuid primary key references public.questions(id) on delete cascade,
 answer jsonb not null
);
create table public.user_progression (
 user_id uuid not null references public.profiles(id) on delete cascade,
 lesson_id integer not null references public.lessons(id) on delete cascade,
 completed boolean not null default false,
 high_score integer not null default 0 check(high_score between 0 and 100),
 completed_at timestamptz, primary key(user_id, lesson_id)
);
create table private.attempts (
 user_id uuid not null references public.profiles(id) on delete cascade,
 lesson_id integer not null references public.lessons(id),
 started_at timestamptz not null default clock_timestamp(),
 primary key(user_id,lesson_id)
);
create index on public.topics(subject_id);
create index on public.lessons(topic_id);
create index on public.questions(lesson_id);
