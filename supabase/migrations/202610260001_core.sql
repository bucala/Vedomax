create function public.begin_lesson(p_lesson_id integer) returns timestamptz
language plpgsql security definer set search_path = '' as $$
declare deadline timestamptz; duration integer;
begin
 if auth.uid() is null then raise exception 'Authentication required'; end if;
 select time_limit_seconds into strict duration from public.lessons where id=p_lesson_id;
 insert into private.attempts(user_id,lesson_id) values(auth.uid(),p_lesson_id)
 on conflict(user_id,lesson_id) do update set started_at=clock_timestamp();
 select started_at + make_interval(secs => duration) into deadline from private.attempts where user_id=auth.uid() and lesson_id=p_lesson_id;
 return deadline;
end $$;

create function public.submit_lesson(p_lesson_id integer, p_answers jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare q record; a jsonb; correct integer:=0; total integer:=0; score integer;
 old_score integer:=0; delta integer; started timestamptz; duration integer; last_day date; today date;
begin
 if auth.uid() is null then raise exception 'Authentication required'; end if;
 if jsonb_typeof(p_answers) <> 'object' or p_answers is null then raise exception 'Invalid answers'; end if;
 -- Lock the profile first to serialize XP and streak updates across lessons.
 perform 1 from public.profiles where id=auth.uid() for update;
 select started_at into started from private.attempts where user_id=auth.uid() and lesson_id=p_lesson_id for update;
 select time_limit_seconds into duration from public.lessons where id=p_lesson_id;
 if started is null or clock_timestamp() > started + make_interval(secs => duration + 5) then raise exception 'Attempt expired; restart lesson'; end if;
 for q in select qu.*, k.answer from public.questions qu join private.question_keys k on k.question_id=qu.id where qu.lesson_id=p_lesson_id loop
  total:=total+1; a:=p_answers->q.id::text;
  if q.mechanic_type='puzzle_calc' and jsonb_typeof(a)='number' then
   if abs((a #>> '{}')::numeric-(q.answer->>'value')::numeric) <= (q.answer->>'tolerance')::numeric then correct:=correct+1; end if;
  elsif q.mechanic_type='detective' and jsonb_typeof(a)='array' then
   if (select coalesce(jsonb_agg(v order by v),'[]'::jsonb) from (select distinct value v from jsonb_array_elements(a)) x)
      = (select jsonb_agg(value order by value) from jsonb_array_elements(q.answer->'indices')) then correct:=correct+1; end if;
  elsif q.mechanic_type='geo_click' and jsonb_typeof(a)='object' then
   if jsonb_typeof(a->'x')='number' and jsonb_typeof(a->'y')='number' then
    if (a->>'x')::numeric between 0 and 1 and (a->>'y')::numeric between 0 and 1
     and power((a->>'x')::numeric-(q.answer->>'x')::numeric,2)+power((a->>'y')::numeric-(q.answer->>'y')::numeric,2) <= power((q.answer->>'radius')::numeric,2) then correct:=correct+1; end if;
   end if;
  end if;
 end loop;
 if total=0 or total<>(select count(*) from public.questions where lesson_id=p_lesson_id) then raise exception 'Lesson not configured for grading'; end if;
 score:=round(100.0*correct/total);
 select high_score into old_score from public.user_progression where user_id=auth.uid() and lesson_id=p_lesson_id;
 delta:=greatest(0,score-coalesce(old_score,0));
 insert into public.user_progression(user_id,lesson_id,completed,high_score,completed_at)
 values(auth.uid(),p_lesson_id,score=100,score,case when score=100 then now() end)
 on conflict(user_id,lesson_id) do update set high_score=greatest(public.user_progression.high_score,excluded.high_score),
 completed=public.user_progression.completed or excluded.completed,
 completed_at=coalesce(public.user_progression.completed_at,excluded.completed_at);
 today:=(now() at time zone 'Europe/Bratislava')::date;
 select (last_active_at at time zone 'Europe/Bratislava')::date into last_day from public.profiles where id=auth.uid();
 update public.profiles set experience_points=experience_points+delta,
 streak_days=case when last_day=today then streak_days when last_day=today-1 then streak_days+1 else 1 end,
 last_active_at=now() where id=auth.uid();
 delete from private.attempts where user_id=auth.uid() and lesson_id=p_lesson_id;
 return jsonb_build_object('score',score,'xp_awarded',delta,'correct',correct,'total',total);
end $$;

-- Opt-in, pseudonymous leaderboard; profile rows remain private.
alter table public.profiles add column leaderboard_visible boolean not null default false;
grant update(leaderboard_visible) on public.profiles to authenticated;
create function public.leaderboard() returns table(username text, experience_points integer)
language sql stable security definer set search_path='' as $$
 select username,experience_points from public.profiles where leaderboard_visible order by experience_points desc,username limit 50
$$;
revoke all on function public.create_profile(), public.begin_lesson(integer), public.submit_lesson(integer,jsonb), public.leaderboard() from public, anon;
grant execute on function public.begin_lesson(integer), public.submit_lesson(integer,jsonb), public.leaderboard() to authenticated;
